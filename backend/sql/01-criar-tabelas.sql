-- Usuarios dos tres perfis do sistema
CREATE TABLE USUARIOS (
    ID          VARCHAR2(10)  NOT NULL,
    NOME        VARCHAR2(100) NOT NULL,
    EMAIL       VARCHAR2(150) NOT NULL,
    SENHA       VARCHAR2(100) NOT NULL,
    PERFIL      VARCHAR2(30)  NOT NULL,
    CRIADO_EM   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UQ_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_PERFIL CHECK (PERFIL IN ('Administrador', 'Líder de Projeto', 'Membro da Equipe'))
);
/

-- Projetos do time. O lider e o usuario responsavel pelo projeto.
CREATE TABLE PROJETOS (
    ID          VARCHAR2(10)  NOT NULL,
    NOME        VARCHAR2(100) NOT NULL,
    DESCRICAO   VARCHAR2(500),
    LIDER_ID    VARCHAR2(10),
    CRIADO_EM   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJETOS PRIMARY KEY (ID),
    CONSTRAINT UQ_PROJETOS_NOME UNIQUE (NOME),
    CONSTRAINT FK_PROJETOS_LIDER FOREIGN KEY (LIDER_ID) REFERENCES USUARIOS (ID)
);
/

-- Demandas do sistema. O status e controlado pelo servidor.
CREATE TABLE DEMANDAS (
    ID                    VARCHAR2(10)   NOT NULL,
    TITULO                VARCHAR2(150)  NOT NULL,
    DESCRICAO             VARCHAR2(1000) NOT NULL,
    TIPO                  VARCHAR2(30)   NOT NULL,
    PRIORIDADE            VARCHAR2(20)   NOT NULL,
    STATUS                VARCHAR2(30)   NOT NULL,
    PROJETO_ID            VARCHAR2(10)   NOT NULL,
    RESPONSAVEL_ID        VARCHAR2(10),
    CRIADA_EM             DATE           NOT NULL,
    ATUALIZADA_EM         DATE           NOT NULL,
    PRAZO                 DATE,
    MOTIVO_CANCELAMENTO   VARCHAR2(500),
    CANCELADA_POR         VARCHAR2(10),
    CANCELADA_EM          TIMESTAMP,
    CONSTRAINT PK_DEMANDAS PRIMARY KEY (ID),
    CONSTRAINT FK_DEMANDAS_PROJETO FOREIGN KEY (PROJETO_ID) REFERENCES PROJETOS (ID),
    CONSTRAINT FK_DEMANDAS_RESPONSAVEL FOREIGN KEY (RESPONSAVEL_ID) REFERENCES USUARIOS (ID),
    CONSTRAINT FK_DEMANDAS_CANCELADA_POR FOREIGN KEY (CANCELADA_POR) REFERENCES USUARIOS (ID),
    CONSTRAINT CK_DEMANDAS_TIPO CHECK (TIPO IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentação')),
    CONSTRAINT CK_DEMANDAS_PRIORIDADE CHECK (PRIORIDADE IN ('Crítica', 'Alta', 'Média', 'Baixa')),
    CONSTRAINT CK_DEMANDAS_STATUS CHECK (STATUS IN ('Aberta', 'Em andamento', 'Em revisão', 'Concluída', 'Cancelada'))
);
/

-- Comentarios feitos na tela de detalhes
CREATE TABLE COMENTARIOS (
    ID          VARCHAR2(10)   NOT NULL,
    DEMANDA_ID  VARCHAR2(10)   NOT NULL,
    AUTOR_ID    VARCHAR2(10)   NOT NULL,
    TEXTO       VARCHAR2(500)  NOT NULL,
    DATA        TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_COMENTARIOS PRIMARY KEY (ID),
    CONSTRAINT FK_COMENTARIOS_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDAS (ID),
    CONSTRAINT FK_COMENTARIOS_AUTOR FOREIGN KEY (AUTOR_ID) REFERENCES USUARIOS (ID)
);
/

-- Historico de alteracoes. Nunca e apagado pelo sistema (so o script
-- de criacao das tabelas apaga tudo para recarregar os dados).
CREATE TABLE HISTORICO (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DEMANDA_ID      VARCHAR2(10)   NOT NULL,
    USUARIO_ID      VARCHAR2(10)   NOT NULL,
    ACAO            VARCHAR2(50)   NOT NULL,
    CAMPO           VARCHAR2(50),
    VALOR_ANTERIOR  VARCHAR2(500),
    VALOR_NOVO      VARCHAR2(500),
    OBSERVACAO      VARCHAR2(500),
    DATA            TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HISTORICO PRIMARY KEY (ID),
    CONSTRAINT FK_HISTORICO_DEMANDA FOREIGN KEY (DEMANDA_ID) REFERENCES DEMANDAS (ID),
    CONSTRAINT FK_HISTORICO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID)
);
/

-- Sessoes do login (token que as telas mandam no cabecalho Authorization)
CREATE TABLE SESSOES (
    TOKEN       VARCHAR2(100) NOT NULL,
    USUARIO_ID  VARCHAR2(10)  NOT NULL,
    CRIADA_EM   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    EXPIRA_EM   TIMESTAMP     NOT NULL,
    CONSTRAINT PK_SESSOES PRIMARY KEY (TOKEN),
    CONSTRAINT FK_SESSOES_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID)
);
/

-- Indices para as consultas mais usadas pelas telas
CREATE INDEX IX_DEMANDAS_PROJETO ON DEMANDAS (PROJETO_ID);
/
CREATE INDEX IX_DEMANDAS_RESPONSAVEL ON DEMANDAS (RESPONSAVEL_ID);
/
CREATE INDEX IX_DEMANDAS_STATUS ON DEMANDAS (STATUS);
/
CREATE INDEX IX_DEMANDAS_PRIORIDADE ON DEMANDAS (PRIORIDADE);
/
CREATE INDEX IX_COMENTARIOS_DEMANDA ON COMENTARIOS (DEMANDA_ID);
/
CREATE INDEX IX_HISTORICO_DEMANDA ON HISTORICO (DEMANDA_ID);
/
CREATE INDEX IX_SESSOES_USUARIO ON SESSOES (USUARIO_ID);
/
